import json,sys
g=json.load(open('plano/plano_svg.json',encoding='utf-8'))
J=lambda v: json.dumps(v,ensure_ascii=False)
L=[]
L.append('/* Plano de lotización real de La Campiña (docs/0019).')
L.append('   Generado desde el «Plano de Lotización y Vías» PTL-01 (Arq. Renzo Tuesta, febrero 2025) con')
L.append('   scripts/plano/README.md. No se edita a mano: si cambia el plano, se vuelve a generar.')
L.append('   Unidades del SVG: lienzo de 1160 × 760; el plano está girado para llenarlo (el norte apunta a `norte`')
L.append('   grados desde arriba, en sentido horario). Cada lote conserva su código (A1…H10) y su forma real;')
L.append('   precio, estado y m² siguen viniendo de src/content/lotes.ts. */')
L.append('')
L.append('export type LoteGeom = { d: string; x: number; y: number; fs: number; ancho: number };')
L.append('export type Rotulo = { texto: string; x: number; y: number; angulo?: number };')
L.append('')
L.append('export const PLANO = {')
L.append(f'  ancho: {g["vw"]},')
L.append(f'  alto: {g["vh"]},')
L.append(f'  /** Grados (horario) desde «arriba» hacia donde apunta el norte. */')
L.append(f'  norte: {g["north"]},')
L.append(f'  metrosPorUnidad: {g["m_per_unit"]},')
L.append(f'  terreno: {J(g["site"])},')
L.append(f'  via: {J(g["road"])},')
x,y,a=g['via']; x2,y2,a2=g['via2']
L.append(f'  viaRotulos: [{{ texto: "Vía a San Nicolás", x: {x}, y: {y}, angulo: {a} }}, {{ texto: "Saltur 6 min · Cayaltí 8 min · Chiclayo 35 min", x: {x2}, y: {y2}, angulo: {a2} }}] as Rotulo[],')
L.append(f'  portico: {{ x: {g["portico"][0]}, y: {g["portico"][1]} }},')
L.append(f'  parques: {J(g["parks"])},')
rx,ry=g['reservoir_label']
L.append(f'  reservorio: {{ d: {J(g["reservoir"])}, x: {rx}, y: {ry} }},')
L.append(f'  /** Bermas de las alamedas, con palmeras. */')
L.append(f'  bermas: {J(g["medians"])},')
L.append('  calles: [')
for n,x,y,a in sorted(g['streets'],key=lambda r:int(r[0].split()[1])): L.append(f'    {{ texto: {J(n)}, x: {x}, y: {y}, angulo: {a} }},')
L.append('  ] as Rotulo[],')
L.append('  amenidades: [')
for t,x,y in g['amen']: L.append(f'    {{ texto: {J(t)}, x: {x}, y: {y} }},')
L.append('  ] as Rotulo[],')
L.append('  /** Rótulo de cada manzana (en una calle o espacio libre junto a ella) y su encuadre para el zoom. */')
L.append('  manzanas: {')
for k in 'ABCDEFGH':
    mx,my=g['mz'][k]; vb=g['mzvb'][k]
    L.append(f'    {k}: {{ x: {mx}, y: {my}, vista: [{vb[0]}, {vb[1]}, {vb[2]}, {vb[3]}] as [number, number, number, number] }},')
L.append('  } as Record<string, { x: number; y: number; vista: [number, number, number, number] }>,')
L.append('  /** Contorno real de cada lote; (x, y) es donde el plano rotula su número; `ancho` es su lado menor en unidades. */')
L.append('  lotes: {')
for lid,d,x,y,fs,w in g['lots']: L.append(f'    {lid}: {{ d: {J(d)}, x: {x}, y: {y}, fs: {fs}, ancho: {w} }},')
L.append('  } as Record<string, LoteGeom>,')
L.append('};')
open(sys.argv[1],'w',encoding='utf-8',newline='\n').write('\n'.join(L)+'\n')
print('escrito',sys.argv[1])
